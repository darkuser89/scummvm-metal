"""Generate Grim/EMI native MSL from the checked-in shader algorithms.

This is an offline development tool. Games use the generated MSL directly.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / 'engines/grim/shaders'
OUTPUT = ROOT / 'engines/grim'
UNIFORM = re.compile(r'uniform\s+(?:highp\s+)?(\w+)\s+(\w+)(?:\[(\w+)\])?\s*;')
INTERFACE = re.compile(r'\b(in|out)\s+(\w+)\s+(\w+)\s*;')
WIDTH = {'float': 1, 'UBOOL': 1, 'vec2': 2, 'vec3': 3, 'vec4': 4, 'mat4': 16}
SHADOW = ['_active', '_color', '_light', '_point', '_normal']


def clean(text):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)


sources = {p.name: clean(p.read_text()) for p in sorted(INPUT.iterdir()) if p.suffix in ('.vertex', '.fragment')}
uniforms = {}
for text in sources.values():
    for kind, name, count in UNIFORM.findall(text):
        if kind == 'shadow_info':
            for field in SHADOW:
                uniforms['shadow.' + field] = (1 if field == '_active' else 3, 1)
        else:
            uniforms[name] = (1 if kind == 'sampler2D' else WIDTH[kind], 8 if count else 1)

license = '/* ScummVM - Graphic Adventure Engine\n * SPDX-License-Identifier: GPL-3.0-or-later\n * Generated by devtools/grim/generate_metal_shaders.py.\n */\n\n'
types = license + '#ifndef GRIM_METAL_SHADER_TYPES_H\n#define GRIM_METAL_SHADER_TYPES_H\n#include "common/scummsys.h"\n#include <stddef.h>\nnamespace Grim { namespace MetalBackend {\nstruct ShaderUniforms {\n    float nativeParameters[4];\n'
msl = '#include <metal_stdlib>\nusing namespace metal;\n#define UBOOL_TEST(x) ((x) != 0)\nstruct Uniforms {\n    float4 nativeParameters;\n'
for name, (width, count) in sorted(uniforms.items()):
    field = name.replace('.', '')
    types += f'    float {field}[{16 if width == 16 else 4}' + (f' * {count}' if count > 1 else '') + '];\n'
    msl += f'    {"float4x4" if width == 16 else "float4"} {field}' + (f'[{count}]' if count > 1 else '') + ';\n'
types += '};\nstruct PackedVertex {float position[4], texcoord[4], color[4], normal[4];};\nstruct UniformBinding {const char *name; uint offset, components, count;};\nstatic const UniformBinding kUniformBindings[] = {\n'
for name, (width, count) in sorted(uniforms.items()):
    types += f'    {{"{name}", offsetof(ShaderUniforms, {name.replace(".", "")}), {width}, {count}}},\n'
types += '};\n} }\n#endif\n'
msl += '};\nstruct InputVertex {packed_float4 position, texcoord, color, normal;};\nstruct VertexOutput {float4 position [[position]]; float2 Texcoord; float4 Color;};\n'


def translate(text, stage, entry):
    local_uniforms = []
    for kind, name, count in UNIFORM.findall(text):
        if kind == 'shadow_info': local_uniforms += ['shadow.' + f for f in SHADOW]
        else: local_uniforms.append(name)
    interfaces = INTERFACE.findall(text)
    text = UNIFORM.sub('', text)
    text = INTERFACE.sub('', text)
    text = re.sub(r'struct\s+shadow_info\s*\{.*?\};', '', text, flags=re.S)
    text = text.replace('OUTPUT', '')
    helper = re.search(r'void checkZBuffer\(\)\s*\{(.*?)\n\}', text, flags=re.S)
    if helper:
        body = helper.group(1)
        text = text[:helper.start()] + text[helper.end():]
        text = text.replace('checkZBuffer();', '{' + body + '}')
    for name in sorted(local_uniforms, key=len, reverse=True):
        width, count = uniforms[name]
        field = 'u.' + name.replace('.', '')
        if count == 1 and width != 16: field += {1: '.x', 2: '.xy', 3: '.xyz', 4: ''}[width]
        text = re.sub(r'(?<![\w.])' + re.escape(name) + r'(?!\w)', field, text)
    # Native sample arguments always use normalized coordinates. The engine retains
    # the original uploaded image orientation and physically flips framebuffer copies.
    text = re.sub(r'\btexture\s*\(\s*u\.texZBuf\.x\s*,', 'image1.sample(filter1,', text)
    text = re.sub(r'\btexture\s*\(\s*u\.tex\.x\s*,', 'image0.sample(filter0,', text)
    text = re.sub(r'\bvec([234])\b', lambda m: 'float' + m[1], text)
    text = re.sub(r'\bmat4\b', 'float4x4', text)
    text = re.sub(r'\bUBOOL\b', 'uint', text)
    text = re.sub(r'\bdiscard\s*;', 'discard_fragment();', text)
    text = text.replace('gl_Position', 'out.position')
    text = text.replace('gl_FragCoord', 'fragmentCoord')
    text = re.sub(r'^const\s+', 'constant ', text, flags=re.M)
    if entry == 'grim_dimFragment':
        text = text.replace('/ 10.0', '* u.dim.x')
        text = text.replace('outColor = float4(val, val, val, 1);', 'outColor = u.dim.x < 0 ? c : float4(val, val, val, 1);')
    if stage == 'vertex':
        args = 'const device InputVertex *vertices [[buffer(0)]], constant Uniforms &u [[buffer(1)]], uint id [[vertex_id]]'
        prolog = 'VertexOutput out = {}; InputVertex v = vertices[id];\n'
        for direction, kind, name in interfaces:
            if direction == 'in':
                width = WIDTH[kind]
                value = f'float4(v.{name})' + (f'.{"xy" if width == 2 else "xyz"}' if width < 4 else '')
                prolog += f'float{width} {name} = {value};\n'
            else: prolog += f'float{WIDTH[kind]} {name} = float{WIDTH[kind]}(0);\n'
        epilog = '\n'
        for direction, kind, name in interfaces:
            if direction == 'out': epilog += f'out.{name} = {name};\n'
        epilog += 'out.position.z = (out.position.z + out.position.w) * 0.5; return out;\n'
        text = re.sub(r'void\s+main\s*\(\s*\)\s*\{', f'vertex VertexOutput {entry}({args}) {{\n' + prolog, text)
    else:
        args = 'VertexOutput in [[stage_in]], constant Uniforms &u [[buffer(1)]], texture2d<float> image0 [[texture(0)]], texture2d<float> image1 [[texture(1)]], sampler filter0 [[sampler(0)]], sampler filter1 [[sampler(1)]]'
        prolog = 'float4 outColor = float4(0); float4 fragmentCoord = float4(in.position.x, u.nativeParameters.x - in.position.y, in.position.zw);\n'
        for direction, kind, name in interfaces:
            if direction == 'in': prolog += f'float{WIDTH[kind]} {name} = in.{name};\n'
        epilog = '\nreturn outColor;\n'
        text = re.sub(r'void\s+main\s*\(\s*\)\s*\{', f'fragment float4 {entry}({args}) {{\n' + prolog, text)
    end = text.rfind('}')
    return text[:end] + epilog + text[end:]


header = license + '#ifndef GRIM_METAL_SHADER_SOURCES_H\n#define GRIM_METAL_SHADER_SOURCES_H\nnamespace Grim { namespace MetalBackend {\nstatic const char *const kShaderPrelude = R"metal(\n' + msl + ')metal";\nstruct ShaderSource {const char *name, *vertexEntry, *fragmentEntry, *source;};\nstatic const ShaderSource kShaderSources[] = {\n'
for filename in sorted(sources):
    if not filename.endswith('.vertex'): continue
    name = filename[:-7]
    vertex = translate(sources[filename], 'vertex', name + 'Vertex')
    fragment = translate(sources[name + '.fragment'], 'fragment', name + 'Fragment')
    header += f'{{"{name}", "{name}Vertex", "{name}Fragment", R"metal(\n{vertex}\n{fragment}\n)metal"}},\n'
header += '};\n} }\n#endif\n'
(OUTPUT / 'metal_shader_types.h').write_text(types)
(OUTPUT / 'metal_shader_sources.h').write_text(header)
