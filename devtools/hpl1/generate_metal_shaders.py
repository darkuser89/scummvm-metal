#!/usr/bin/env python3
"""Generate native MSL sources for the HPL1 shader catalog (no runtime GLSL)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SHADERS = ROOT / 'engines/hpl1/engine/impl/shaders'
DEST = ROOT / 'engines/hpl1/engine/impl/metal_shader_sources.h'
TYPES = ROOT / 'engines/hpl1/engine/impl/metal_shader_types.h'


def source(path):
    text = path.read_text()
    text = re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)
    # Repair two incomplete declarations and spelling errors in the legacy
    # catalog before producing the independent native shader representation.
    text = re.sub(r'(?m)^(\s*(?:in|out|uniform)\s+\w+\s+\w+)\s*$', r'\1;', text)
    text = text.replace('vLighttDir', 'vLightDir')
    if path.name == 'hpl1_BumpSpec2D_Light.fragment':
        text = re.sub(r'\buv\b', 'vUv.xy', text)
    if path.name == 'hpl1_Diffuse_ColorMul.vertex':
        text = text.replace('color * colorMul', 'color * colorMul.xyz')
    return text


def width(kind):
    return int(kind[-1]) if kind.startswith('vec') else 1


catalog = [(p, source(p)) for p in sorted(SHADERS.iterdir()) if p.suffix in ('.vertex', '.fragment')]
uniforms = {}
varyings = {}
for path, text in catalog:
    for kind, name in re.findall(r'\buniform\s+(\w+)\s+(\w+)\s*;', text):
        if not kind.startswith('sampler'):
            uniforms[name] = kind
    for kind, name in re.findall(r'\b(?:in|out)\s+(float|vec[234])\s+(\w+)\s*;', text):
        varyings[name] = max(varyings.get(name, 1), width(kind))

prefix = '''/* ScummVM - Graphic Adventure Engine
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * Generated by devtools/hpl1/generate_metal_shaders.py.
 * Shader algorithms: Copyright (C) 2006-2010 Frictional Games.
 */
'''
cpp = prefix + '\n#ifndef HPL_METAL_SHADER_TYPES_H\n#define HPL_METAL_SHADER_TYPES_H\n\n#include "common/scummsys.h"\n#include <stddef.h>\n\nnamespace hpl {\n\n'
cpp += '''struct MetalTextureEnvironment {
    uint32 functions[4], rgbSources[4], alphaSources[4], rgbOperands[4], alphaOperands[4];
    float color[4];
};
struct MetalShaderUniforms {
    float mvp[16], backendModelView[16], textureMatrices[8][16], currentColor[4], nativeParameters[4];
    float textureSizes[8][4], clipPlanes[6][4];
    uint32 controls[4];
    MetalTextureEnvironment environments[8];
'''
msl = '''#include <metal_stdlib>
using namespace metal;
struct Environment {
    uint4 functions, rgbSources, alphaSources, rgbOperands, alphaOperands;
    float4 color;
};
struct Uniforms {
    float4x4 mvp, backendModelView, textureMatrices[8];
    float4 currentColor, nativeParameters, textureSizes[8], clipPlanes[6];
    uint4 controls;
    Environment environments[8];
'''
for name, kind in sorted(uniforms.items()):
    cpp += '    float ' + name + ('[16];\n' if kind == 'mat4' else '[4];\n')
    msl += '    ' + ('float4x4' if kind == 'mat4' else 'float4') + ' ' + name + ';\n'
cpp += '};\n\nstruct MetalUniformBinding {const char *name; uint offset, components;};\nstatic const MetalUniformBinding kMetalUniformBindings[] = {\n'
for name, kind in sorted(uniforms.items()):
    cpp += '    {"%s", offsetof(MetalShaderUniforms, %s), %d},\n' % (name, name, 16 if kind == 'mat4' else width(kind))
cpp += '};\n\nstruct MetalShaderVertex {float position[4], normal[4], color[4], texcoord[8][4];};\n\n} // End of namespace hpl\n\n#endif\n'
TYPES.write_text(cpp)
msl += '''};
struct Vertex {packed_float4 position, normal, color; packed_float4 texcoord[8];};
'''
for struct_name in ['VertexOutput', 'FragmentInput']:
    msl += 'struct ' + struct_name + ' {\n    float4 position [[position]];\n'
    for index, (name, n) in enumerate(sorted(varyings.items())):
        msl += '    %s %s [[user(locn%d)]];\n' % ('float' if n == 1 else 'float%d' % n, name, index)
    if struct_name == 'VertexOutput':
        msl += '    float clipDistances [[clip_distance]] [6];\n'
    msl += '};\n'
msl += '''float4 sample1D(texture2d<float> image, sampler filtering, float uv, float4 size) {
    return image.sample(filtering, float2(uv, 0.5));
}
float4 sample2D(texture2d<float> image, sampler filtering, float2 uv, float4 size) {
    if (size.w != 0) uv.y = 1 - uv.y;
    return image.sample(filtering, uv);
}
float4 sample2D(texture2d<float> image, sampler filtering, float3 uv, float4 size) {
    return sample2D(image, filtering, uv.xy, size);
}
float3x3 upper3x3(float4x4 matrix) {
    return float3x3(matrix[0].xyz, matrix[1].xyz, matrix[2].xyz);
}
float4 sampleRect(texture2d<float> image, sampler filtering, float2 uv, float4 size) {
    uv /= size.xy;
    if (size.w != 0) uv.y = 1 - uv.y;
    return image.sample(filtering, uv);
}
float4 sampleCube(texturecube<float> image, sampler filtering, float3 uv, float4 size) {
    return image.sample(filtering, uv);
}
float4 sample3D(texture3d<float> image, sampler filtering, float3 uv, float4 size) {
    return image.sample(filtering, uv);
}
void alphaTest(float alpha, constant Uniforms &u) {
    uint function = uint(u.nativeParameters.z);
    float ref = u.nativeParameters.y;
    bool pass = function == 7 || (function == 1 && alpha < ref) || (function == 2 && alpha == ref) ||
                (function == 3 && alpha <= ref) || (function == 4 && alpha > ref) ||
                (function == 5 && alpha != ref) || (function == 6 && alpha >= ref);
    if (!pass) discard_fragment();
}
'''
entries = []
for path, text in catalog:
    stem = path.stem.removeprefix('hpl1_')
    entry = ('vertex_' if path.suffix == '.vertex' else 'fragment_') + re.sub(r'\W', '_', stem)
    declarations = re.findall(r'\b(?:in|out)\s+(float|vec[234])\s+(\w+)\s*;', text)
    samplers = {name: kind for kind, name in re.findall(r'\buniform\s+(sampler\w+)\s+(\w+)\s*;', text)}
    text = re.sub(r'\b(?:in|out|uniform)\s+\w+\s+\w+\s*;', '', text)
    text = re.sub(r'\bOUTPUT\b', '', text)
    head, rest = re.split(r'\bvoid\s+main\s*\(\s*\)', text, maxsplit=1)
    body = rest[rest.index('{') + 1:rest.rfind('}')]
    body = head + '\n' + body
    body = re.sub(r'\.([stpq]+)\b', lambda m: '.' + m[1].translate(str.maketrans('stpq', 'xyzw')), body)
    for name, kind in sorted(uniforms.items()):
        suffix = '' if kind == 'mat4' else '.' + ('x' if width(kind) == 1 else 'xyzw'[:width(kind)])
        body = re.sub(r'\b' + name + r'\b', 'u.' + name + suffix, body)
    body = re.sub(r'\bvec([234])\b', r'float\1', body)
    body = re.sub(r'\bmat([34])\b', r'float\1x\1', body)
    body = body.replace('float3x3(u.', 'upper3x3(u.')
    body = re.sub(r'\bfixed\b', 'float', body)
    for name, kind in samplers.items():
        fn = {'sampler1D':'sample1D','sampler2D':'sample2D','sampler2DRect':'sampleRect','samplerCube':'sampleCube','sampler3D':'sample3D'}[kind]
        # Texture expressions may contain nested calls and commas.
        pattern = re.compile(r'\btexture(?:1D|2DRect|3D|Cube)?\s*\(\s*' + name + r'\s*,')
        while match := pattern.search(body):
            pos = match.end(); depth = 1
            while depth:
                if body[pos] == '(': depth += 1
                elif body[pos] == ')': depth -= 1
                pos += 1
            coordinate = body[match.end():pos-1]
            index = int(name[3:])
            body = body[:match.start()] + '%s(%s, sampler%d, %s, u.textureSizes[%d])' % (fn,name,index,coordinate,index) + body[pos:]
    if path.suffix == '.vertex':
        body = body.replace('gl_Vertex','float4(inputVertex.position)').replace('gl_Normal','float3(float4(inputVertex.normal).xyz)').replace('gl_Color','float4(inputVertex.color)')
        for index in range(8): body = body.replace('gl_MultiTexCoord%d' % index, 'float4(inputVertex.texcoord[%d])' % index)
        body = body.replace('gl_Position','output.position')
        local = ''.join('    %s %s = %s(0);\n' % ('float' if width(kind)==1 else 'float%d'%width(kind),name,'float' if width(kind)==1 else 'float%d'%width(kind)) for kind,name in declarations)
        finish = ''
        for kind,name in declarations:
            have, need = width(kind), varyings[name]
            value = name
            if have < need: value = 'float%d(%s%s)' % (need, name, ', 0' * (need-have))
            finish += '    output.%s = %s;\n' % (name,value)
        finish += '''    float4 eye = u.backendModelView * float4(inputVertex.position);
    for (uint i = 0; i < 6; ++i) output.clipDistances[i] = (u.controls.x & (1u << i)) ? dot(eye, u.clipPlanes[i]) : 1;
    output.position.z = (output.position.z + output.position.w) * 0.5;
    return output;
'''
        code = 'vertex VertexOutput %s(uint id [[vertex_id]], const device Vertex *vertices [[buffer(0)]], constant Uniforms &u [[buffer(1)]]) {\n    const device Vertex &inputVertex = vertices[id];\n    VertexOutput output = {};\n' % entry + local + body + '\n' + finish + '}\n'
    else:
        body = body.replace('gl_FragCoord','float4(input.position.x, u.nativeParameters.x - input.position.y, input.position.z, input.position.w)')
        local = '    float4 outColor = float4(0);\n'
        for kind,name in declarations:
            suffix = '' if width(kind) == varyings[name] else '.' + ('x' if width(kind) == 1 else 'xyzw'[:width(kind)])
            local += '    %s %s = input.%s%s;\n' % ('float' if width(kind)==1 else 'float%d'%width(kind),name,name,suffix)
        bindings = ''
        for name, kind in sorted(samplers.items()):
            index = int(name[3:]); target = 'texturecube' if kind == 'samplerCube' else 'texture3d' if kind == 'sampler3D' else 'texture2d'
            bindings += ', %s<float> %s [[texture(%d)]], sampler sampler%d [[sampler(%d)]]' % (target,name,index,index,index)
        code = 'fragment float4 %s(FragmentInput input [[stage_in]], constant Uniforms &u [[buffer(1)]]%s) {\n' % (entry,bindings) + local + body + '\n    alphaTest(outColor.a, u);\n    return outColor;\n}\n'
    kinds = {'sampler1D': 1, 'sampler2D': 2, 'sampler2DRect': 3, 'samplerCube': 4, 'sampler3D': 5}
    texture_kinds = [kinds.get(samplers.get('tex%d' % i), 0) for i in range(8)]
    entries.append((stem,path.suffix[1:],entry,code,texture_kinds))
result = prefix + '\n#ifndef HPL_METAL_SHADER_SOURCES_H\n#define HPL_METAL_SHADER_SOURCES_H\n\nnamespace hpl {\n\nstatic const char *const kMetalShaderPrelude = R"metal(\n' + msl + ')metal";\n\n'
for stem, stage, entry, code, texture_kinds in entries:
    result += 'static const char *const source_%s = R"metal(\n%s)metal";\n\n' % (entry,code)
result += 'struct MetalShaderSource {const char *name, *stage, *entry, *source; uint8 textureKinds[8];};\nstatic const MetalShaderSource kMetalShaderSources[] = {\n'
for stem, stage, entry, code, texture_kinds in entries:
    result += '    {"%s", "%s", "%s", source_%s, {%s}},\n' % (stem,stage,entry,entry,', '.join(map(str,texture_kinds)))
result += '};\n\n} // End of namespace hpl\n\n#endif\n'
DEST.write_text(result)
